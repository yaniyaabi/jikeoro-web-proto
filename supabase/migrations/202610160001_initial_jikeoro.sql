begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  role text not null default 'member' check (role in ('member', 'research_admin', 'agency_staff')),
  agency text,
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  source text not null check (source in ('senior_app', 'website')),
  category text not null,
  subcategory text,
  title text not null,
  description text not null default '',
  latitude double precision,
  longitude double precision,
  accuracy double precision,
  address text,
  place_description text,
  status text not null default 'received' check (status in ('received', 'review', 'action', 'completed')),
  assigned_agency text,
  response text,
  observed_at timestamptz,
  weather jsonb,
  points integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.report_media (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('image', 'video', 'audio')),
  storage_path text not null unique,
  original_name text not null,
  mime_type text not null,
  size_bytes bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.report_status_history (
  id bigint generated by default as identity primary key,
  report_id uuid not null references public.reports(id) on delete cascade,
  status text not null check (status in ('received', 'review', 'action', 'completed')),
  note text,
  actor_user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid not null references public.profiles(id) on delete restrict,
  report_id uuid references public.reports(id) on delete set null,
  action text not null,
  detail text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists reports_user_created_idx on public.reports(user_id, created_at desc);
create index if not exists reports_map_idx on public.reports(latitude, longitude) where latitude is not null and longitude is not null;
create index if not exists report_media_report_idx on public.report_media(report_id, created_at);
create index if not exists report_history_report_idx on public.report_status_history(report_id, created_at);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(coalesce(new.email, ''), '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.set_report_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists reports_set_updated_at on public.reports;
create trigger reports_set_updated_at
before update on public.reports
for each row execute procedure public.set_report_updated_at();

create or replace function public.is_jikeoro_staff()
returns boolean
language sql
stable
security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('research_admin', 'agency_staff')
  );
$$;

alter table public.profiles enable row level security;
alter table public.reports enable row level security;
alter table public.report_media enable row level security;
alter table public.report_status_history enable row level security;
alter table public.admin_audit_logs enable row level security;

drop policy if exists "profile self or staff read" on public.profiles;
create policy "profile self or staff read" on public.profiles
for select to authenticated using (id = auth.uid() or public.is_jikeoro_staff());

drop policy if exists "report owner or staff read" on public.reports;
create policy "report owner or staff read" on public.reports
for select to authenticated using (user_id = auth.uid() or public.is_jikeoro_staff());

drop policy if exists "report owner insert" on public.reports;
create policy "report owner insert" on public.reports
for insert to authenticated with check (user_id = auth.uid());

drop policy if exists "staff update reports" on public.reports;
create policy "staff update reports" on public.reports
for update to authenticated using (public.is_jikeoro_staff()) with check (public.is_jikeoro_staff());

drop policy if exists "report owner delete" on public.reports;
create policy "report owner delete" on public.reports
for delete to authenticated using (user_id = auth.uid() or public.is_jikeoro_staff());

drop policy if exists "media owner or staff read" on public.report_media;
create policy "media owner or staff read" on public.report_media
for select to authenticated using (user_id = auth.uid() or public.is_jikeoro_staff());

drop policy if exists "media owner insert" on public.report_media;
create policy "media owner insert" on public.report_media
for insert to authenticated with check (
  user_id = auth.uid()
  and exists (select 1 from public.reports where id = report_id and user_id = auth.uid())
);

drop policy if exists "media owner or staff delete" on public.report_media;
create policy "media owner or staff delete" on public.report_media
for delete to authenticated using (user_id = auth.uid() or public.is_jikeoro_staff());

drop policy if exists "history owner or staff read" on public.report_status_history;
create policy "history owner or staff read" on public.report_status_history
for select to authenticated using (
  public.is_jikeoro_staff()
  or exists (select 1 from public.reports where id = report_id and user_id = auth.uid())
);

drop policy if exists "staff insert history" on public.report_status_history;
create policy "staff insert history" on public.report_status_history
for insert to authenticated with check (public.is_jikeoro_staff());

drop policy if exists "staff read audit logs" on public.admin_audit_logs;
create policy "staff read audit logs" on public.admin_audit_logs
for select to authenticated using (public.is_jikeoro_staff());

drop policy if exists "staff insert audit logs" on public.admin_audit_logs;
create policy "staff insert audit logs" on public.admin_audit_logs
for insert to authenticated with check (public.is_jikeoro_staff() and actor_user_id = auth.uid());

