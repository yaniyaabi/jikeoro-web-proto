CREATE SCHEMA IF NOT EXISTS jikeoro;
CREATE TABLE IF NOT EXISTS jikeoro.schema_versions (version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS jikeoro.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL CHECK (length(email) <= 254),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'member' CHECK (role IN ('member','research_admin','agency_staff')),
  agency text,
  avatar jsonb NOT NULL DEFAULT '{}',
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (role <> 'agency_staff' OR COALESCE(length(trim(agency)) > 0,false))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_idx ON jikeoro.users (lower(email));
CREATE TABLE IF NOT EXISTS jikeoro.sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES jikeoro.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON jikeoro.sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON jikeoro.sessions(expires_at);
CREATE TABLE IF NOT EXISTS jikeoro.reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES jikeoro.users(id),
  source text NOT NULL CHECK(source IN ('senior_app','website')),
  category text NOT NULL,
  subcategory text,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  latitude double precision CHECK(latitude BETWEEN -90 AND 90),
  longitude double precision CHECK(longitude BETWEEN -180 AND 180),
  accuracy double precision CHECK(accuracy >= 0 AND accuracy <= 1000000),
  address text,
  place_description text,
  status text NOT NULL DEFAULT 'received' CHECK(status IN ('received','review','action','completed')),
  assigned_agency text,
  response text NOT NULL DEFAULT '기록이 안전하게 접수됐어요. 위치와 내용을 확인한 뒤 담당 기관을 연결할게요.',
  observed_at timestamptz,
  weather jsonb,
  points integer NOT NULL DEFAULT 100 CHECK(points = 100),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((latitude IS NULL) = (longitude IS NULL))
);
CREATE INDEX IF NOT EXISTS reports_user_idx ON jikeoro.reports(user_id,created_at DESC);
CREATE INDEX IF NOT EXISTS reports_map_idx ON jikeoro.reports(created_at DESC) WHERE latitude IS NOT NULL;
CREATE TABLE IF NOT EXISTS jikeoro.media (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES jikeoro.reports(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK(kind IN ('image','video','audio')),
  original_name text NOT NULL,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK(size_bytes > 0),
  storage_path text NOT NULL UNIQUE,
  preview_path text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS media_report_idx ON jikeoro.media(report_id,created_at);
CREATE TABLE IF NOT EXISTS jikeoro.report_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id uuid NOT NULL REFERENCES jikeoro.reports(id) ON DELETE CASCADE,
  status text NOT NULL CHECK(status IN ('received','review','action','completed')),
  note text,
  actor_user_id uuid REFERENCES jikeoro.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jikeoro.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid NOT NULL REFERENCES jikeoro.users(id),
  report_id uuid REFERENCES jikeoro.reports(id) ON DELETE SET NULL,
  action text NOT NULL,
  detail text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jikeoro.file_cleanup (
  file_path text PRIMARY KEY,
  requested_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jikeoro.rewards (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES jikeoro.users(id),
  phone text NOT NULL CHECK(phone ~ '^[0-9]{10,11}$'),
  exchange_points integer NOT NULL DEFAULT 500 CHECK(exchange_points = 500),
  earned_points integer NOT NULL DEFAULT 0,
  source text NOT NULL CHECK(source IN ('app','web')),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent')),
  requested_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS reward_pending_idx ON jikeoro.rewards(user_id) WHERE status='pending';
CREATE TABLE IF NOT EXISTS jikeoro.push_subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES jikeoro.users(id) ON DELETE CASCADE,
  session_hash text NOT NULL REFERENCES jikeoro.sessions(token_hash) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  p256dh text NOT NULL,
  auth text NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  last_test_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jikeoro.push_deliveries (
  subscription_id uuid NOT NULL REFERENCES jikeoro.push_subscriptions(id) ON DELETE CASCADE,
  local_date date NOT NULL,
  hour integer NOT NULL CHECK(hour IN (11,19)),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(subscription_id,local_date,hour)
);
INSERT INTO jikeoro.schema_versions(version) VALUES(1) ON CONFLICT DO NOTHING;
